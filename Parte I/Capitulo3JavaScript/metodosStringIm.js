String.prototype.indexOf(); // Localiza o índice da primeira ocorrência de um valor especificado em uma string. Retorna -1 se o valor não for encontrado.

String.prototype.lastIndexOf(); // Localiza o índice da última ocorrência de um valor especificado em uma string. Retorna -1 se o valor não for encontrado.

String.prototype.search(); // Localiza a posição de uma string dentro de outra string. Retorna -1 se o valor não for encontrado.

String.prototype.includes(); // Verifica se uma string contém outra string. Retorna true se a string for encontrada, caso contrário, retorna false.

String.prototype.match(); // Retorna um array contendo todas as ocorrências de uma expressão regular em uma string. Retorna null se não houver correspondência.

String.prototype.matchAll(); // Retorna um array contendo todas as correspondências de uma expressão regular em uma string. Retorna null se não houver correspondência.

String.prototype.split(); // Divide uma string em um array de substrings com base em um separador especificado. Retorna um array de substrings.

String.prototype.slice(); // Extrai uma parte de uma string e retorna uma nova string. Aceita dois parâmetros: o índice inicial e o índice final (opcional).

String.prototype.trim(); // Remove os espaços em branco do início e do final de uma string. Retorna uma nova string sem os espaços em branco.

String.prototype.replace(); // Substitui uma parte de uma string por outra string. Aceita dois parâmetros: o valor a ser substituído e o valor de substituição. Retorna uma nova string com as substituições feitas.